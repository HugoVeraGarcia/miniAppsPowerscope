/* PowerScope — progressive enhancement layer.
   Every page renders fully without JS; this file adds the comparator,
   the compare tray, gallery, sorting and the mobile menu.
   Data comes from window.__DB__ (generated by tools/build.py). */
(function () {
  "use strict";

  var DB = window.__DB__ || { products: [], meta: { axes: [], groups: [], colors: [], max: 4 } };
  var BY_ID = {};
  DB.products.forEach(function (p) { BY_ID[p.id] = p; });
  var MAX = DB.meta.max || 4;
  var KEY = "ps-compare-v1";

  function safe(fn, name) {
    try { fn(); } catch (e) { if (window.console) console.warn("[PowerScope] " + name + " failed", e); }
  }
  function $(s, r) { return (r || document).querySelector(s); }
  function $$(s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); }
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function money(v) { return v == null ? "" : "$" + v.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 }); }
  function num(v) { return typeof v === "number" ? v.toLocaleString("en-US") : v; }

  /* ---------- compare list (localStorage, per viewer) ---------- */
  var store = {
    get: function () {
      try {
        var v = JSON.parse(localStorage.getItem(KEY) || "[]");
        return Array.isArray(v) ? v.filter(function (id) { return BY_ID[id]; }).slice(0, MAX) : [];
      } catch (e) { return []; }
    },
    set: function (ids) {
      try { localStorage.setItem(KEY, JSON.stringify(ids.slice(0, MAX))); } catch (e) { /* private mode */ }
      document.dispatchEvent(new CustomEvent("cmp:change"));
    }
  };
  var memo = null; // fallback when storage is unavailable
  function getList() { var l = store.get(); if (!l.length && memo) return memo.slice(); return l; }
  function setList(ids) { memo = ids.slice(0, MAX); store.set(memo); }
  function toggle(id) {
    var l = getList();
    var i = l.indexOf(id);
    if (i > -1) l.splice(i, 1);
    else {
      if (l.length >= MAX) { flash("You can compare up to " + MAX + " power stations. Remove one first."); return; }
      l.push(id);
    }
    setList(l);
  }

  var flashEl;
  function flash(msg) {
    if (!flashEl) {
      flashEl = document.createElement("div");
      flashEl.setAttribute("role", "status");
      flashEl.style.cssText = "position:fixed;left:50%;top:84px;transform:translateX(-50%);z-index:60;background:#0B0D12;color:#fff;padding:10px 16px;border-radius:999px;font:500 .9rem Inter,sans-serif;box-shadow:0 10px 30px -10px rgba(0,0,0,.5);transition:opacity .25s;max-width:92vw;text-align:center";
      document.body.appendChild(flashEl);
    }
    flashEl.textContent = msg;
    flashEl.style.opacity = "1";
    clearTimeout(flash.t);
    flash.t = setTimeout(function () { flashEl.style.opacity = "0"; }, 2600);
  }

  /* ---------- nav ---------- */
  function initNav() {
    var btn = $(".nav-toggle"), nav = $("#site-nav");
    if (!btn || !nav) return;
    btn.addEventListener("click", function () {
      var open = nav.classList.toggle("is-open");
      btn.setAttribute("aria-expanded", open ? "true" : "false");
    });
    document.addEventListener("keydown", function (e) {
      if (e.key === "Escape" && nav.classList.contains("is-open")) { nav.classList.remove("is-open"); btn.setAttribute("aria-expanded", "false"); btn.focus(); }
    });
  }

  /* ---------- compare toggles + tray ---------- */
  function renderToggles() {
    var l = getList();
    $$("[data-compare]").forEach(function (b) {
      var on = l.indexOf(b.getAttribute("data-compare")) > -1;
      b.setAttribute("aria-pressed", on ? "true" : "false");
      b.title = on ? "Remove from comparison" : "Add to comparison";
      var use = b.querySelector("use");
      if (use) use.setAttribute("href", on ? "#i-check" : "#i-plus");
      var t = b.querySelector(".cmp-toggle__txt");
      if (t) t.textContent = on ? "In comparison" : "Compare";
    });
    $$("[data-cmp-count]").forEach(function (c) { c.textContent = l.length; c.hidden = !l.length; });

    var tray = $("[data-cmp-tray]");
    if (!tray) return;
    var onComparePage = !!$("[data-comparator]");
    var show = l.length > 0 && !onComparePage;
    tray.hidden = !show;
    document.body.classList.toggle("has-tray", show);
    $("[data-cmp-items]", tray).innerHTML = l.map(function (id) {
      var p = BY_ID[id];
      return '<div class="cmp-tray__item"><img src="' + esc(p.img) + '" alt=""><span>' + esc(p.name) + '</span>' +
        '<button type="button" data-cmp-remove="' + esc(id) + '" aria-label="Remove ' + esc(p.name) + '"><svg class="ico"><use href="#i-x"/></svg></button></div>';
    }).join("");
    var go = $("[data-cmp-go]", tray);
    go.href = "/compare/#ids=" + l.join(",");
    go.classList.toggle("is-disabled", l.length < 2);
  }
  function initCompareToggles() {
    document.addEventListener("click", function (e) {
      var t = e.target.closest ? e.target.closest("[data-compare],[data-cmp-remove],[data-cmp-clear]") : null;
      if (!t) return;
      if (t.hasAttribute("data-compare")) {
        var id = t.getAttribute("data-compare");
        var before = getList().length;
        toggle(id);
        var after = getList().length;
        if (after > before && after === 1) flash("Added. Pick one more power station to compare.");
      } else if (t.hasAttribute("data-cmp-remove")) {
        toggle(t.getAttribute("data-cmp-remove"));
      } else {
        setList([]);
      }
    });
    document.addEventListener("cmp:change", renderToggles);
    window.addEventListener("storage", function (e) { if (e.key === KEY) renderToggles(); });
    renderToggles();
  }

  /* ---------- gallery ---------- */
  function initGallery() {
    $$("[data-gallery]").forEach(function (g) {
      var main = $("[data-gallery-main]", g);
      var thumbs = $$(".gallery__thumb", g);
      if (!main || !thumbs.length) return;
      var idx = 0;
      function show(i) {
        idx = (i + thumbs.length) % thumbs.length;
        thumbs.forEach(function (t, j) { t.classList.toggle("is-active", j === idx); });
        var src = thumbs[idx].getAttribute("data-src");
        if (main.getAttribute("src") === src) return;
        main.classList.add("is-loading");
        var im = new Image();
        im.onload = im.onerror = function () { main.src = src; main.classList.remove("is-loading"); };
        im.src = src;
      }
      thumbs.forEach(function (t, i) { t.addEventListener("click", function () { show(i); }); });
      g.addEventListener("keydown", function (e) {
        if (e.key === "ArrowRight") { show(idx + 1); e.preventDefault(); }
        if (e.key === "ArrowLeft") { show(idx - 1); e.preventDefault(); }
      });
      // swipe on the main image
      var x0 = null;
      main.addEventListener("touchstart", function (e) { x0 = e.touches[0].clientX; }, { passive: true });
      main.addEventListener("touchend", function (e) {
        if (x0 == null) return;
        var dx = e.changedTouches[0].clientX - x0;
        if (Math.abs(dx) > 40) show(idx + (dx < 0 ? 1 : -1));
        x0 = null;
      });
    });
  }

  /* ---------- sorting on listing pages ---------- */
  function initSort() {
    $$("[data-sort-bar]").forEach(function (bar) {
      var grid = bar.parentNode.querySelector("[data-sortable]");
      var sel = $("[data-sort]", bar);
      if (!grid || !sel) return;
      sel.addEventListener("change", function () {
        var v = sel.value;
        var cards = $$(".card", grid);
        var n = function (c, k) { return parseFloat(c.getAttribute("data-" + k)) || 0; };
        var cmp = {
          "score": function (a, b) { return n(b, "score") - n(a, "score"); },
          "price-asc": function (a, b) { return (n(a, "price") || 1e9) - (n(b, "price") || 1e9); },
          "price-desc": function (a, b) { return n(b, "price") - n(a, "price"); },
          "speed": function (a, b) { return n(b, "speed") - n(a, "speed"); },
          "range": function (a, b) { return n(b, "range") - n(a, "range"); },
          "weight": function (a, b) { return n(a, "weight") - n(b, "weight"); },
          "rating": function (a, b) { return n(b, "rating") - n(a, "rating"); }
        }[v];
        cards.sort(cmp).forEach(function (c) { grid.appendChild(c); });
      });
    });
  }

  /* ---------- sticky buy bar on mobile product pages ---------- */
  function initStickyBuy() {
    var bar = $("[data-sticky-buy]"), box = $(".buybox");
    if (!bar || !box || !("IntersectionObserver" in window)) return;
    var io = new IntersectionObserver(function (en) {
      bar.classList.toggle("is-visible", !en[0].isIntersecting && en[0].boundingClientRect.top < 0);
    }, { threshold: 0 });
    io.observe(box);
  }

  /* ---------- radar (same geometry as the build script) ---------- */
  function radar(series, size) {
    var axes = DB.meta.axes, n = axes.length, cx = size / 2, cy = size / 2, r = size * 0.34;
    function pt(i, v) {
      return [cx + r * (v / 10) * Math.sin(2 * Math.PI * i / n), cy - r * (v / 10) * Math.cos(2 * Math.PI * i / n)];
    }
    function poly(v) { return axes.map(function (_, i) { var p = pt(i, v); return p[0].toFixed(1) + "," + p[1].toFixed(1); }).join(" "); }
    var s = '<svg class="radar" viewBox="0 0 ' + size + " " + size + '" role="img" aria-label="Overlaid editor scores">';
    [2, 4, 6, 8, 10].forEach(function (v) { s += '<polygon class="radar__ring" points="' + poly(v) + '"/>'; });
    axes.forEach(function (_, i) { var p = pt(i, 10); s += '<line class="radar__spoke" x1="' + cx + '" y1="' + cy + '" x2="' + p[0].toFixed(1) + '" y2="' + p[1].toFixed(1) + '"/>'; });
    series.forEach(function (se) {
      var pts = axes.map(function (a, i) { var p = pt(i, se.scores[a.k] || 0); return p[0].toFixed(1) + "," + p[1].toFixed(1); }).join(" ");
      s += '<polygon class="radar__area" points="' + pts + '" style="--c:' + se.color + '"/>';
      axes.forEach(function (a, i) {
        var v = se.scores[a.k], p = pt(i, v || 0);
        s += '<circle class="radar__dot' + (v == null ? " radar__dot--na" : "") + '" cx="' + p[0].toFixed(1) + '" cy="' + p[1].toFixed(1) + '" r="3.2" style="--c:' + se.color + '"><title>' + esc(se.name) + " · " + a.label + ": " + (v == null ? "n/a" : v) + "</title></circle>";
      });
    });
    axes.forEach(function (a, i) {
      var p = pt(i, 12.6), anchor = Math.abs(p[0] - cx) < 4 ? "middle" : (p[0] > cx ? "start" : "end");
      s += '<text class="radar__label" x="' + p[0].toFixed(1) + '" y="' + p[1].toFixed(1) + '" text-anchor="' + anchor + '">' + esc(a.label) + "</text>";
    });
    return s + "</svg>";
  }

  /* ---------- comparator ---------- */
  function initComparator() {
    var root = $("[data-comparator]");
    if (!root) return;
    var picker = $("[data-cmp-picker]", root), list = $("[data-cmp-options]", root), out = $("[data-cmp-result]", root);
    var search = $("[data-cmp-search]", root), pickedLbl = $("[data-cmp-picked]", root);
    var colors = DB.meta.colors;
    var showAll = false;

    function fromHash() {
      var m = location.hash.match(/ids=([^&]+)/);
      if (!m) return null;
      var ids = decodeURIComponent(m[1]).split(",").filter(function (id) { return BY_ID[id]; });
      return ids.length ? ids.slice(0, MAX) : null;
    }
    var sel = fromHash() || getList();
    if (!sel.length) {
      sel = DB.products.slice().sort(function (a, b) { return b.score - a.score; }).slice(0, 2).map(function (p) { return p.id; });
    }
    setList(sel);

    picker.hidden = false;
    list.innerHTML = DB.products.map(function (p) {
      return '<button type="button" class="opt" data-opt="' + esc(p.id) + '" aria-pressed="false"><img src="' + esc(p.img) + '" alt="" loading="lazy"><span>' + esc(p.name) + "</span><small>" + esc(p.brand) + (p.price != null ? " · " + money(p.price) : "") + "</small></button>";
    }).join("");

    list.addEventListener("click", function (e) {
      var b = e.target.closest("[data-opt]");
      if (!b || b.disabled) return;
      var id = b.getAttribute("data-opt"), l = getList(), i = l.indexOf(id);
      if (i > -1) l.splice(i, 1); else if (l.length < MAX) l.push(id);
      setList(l);
    });
    if (search) search.addEventListener("input", function () {
      var q = search.value.trim().toLowerCase();
      $$("[data-opt]", list).forEach(function (b) {
        var p = BY_ID[b.getAttribute("data-opt")];
        b.hidden = q && (p.name + " " + p.brand).toLowerCase().indexOf(q) === -1;
      });
    });
    out.addEventListener("click", function (e) {
      var rm = e.target.closest("[data-rm]");
      if (rm) { var l = getList(); l.splice(l.indexOf(rm.getAttribute("data-rm")), 1); setList(l); }
    });
    out.addEventListener("change", function (e) {
      if (e.target.matches("[data-diff]")) { showAll = !e.target.checked; var t = $(".cmp-table", out); if (t) t.classList.toggle("show-all", showAll); }
    });
    document.addEventListener("cmp:change", render);
    window.addEventListener("hashchange", function () { var h = fromHash(); if (h) setList(h); });
    render();

    function fmt(v, unit) {
      if (v == null) return '<span class="na" title="Not published by the manufacturer">—</span>';
      if (unit === "bool") return v ? '<span class="yes">Yes</span>' : '<span class="no">No</span>';
      if (unit) return num(v) + " " + unit;
      return esc(v);
    }

    function render() {
      var ids = getList();
      var items = ids.map(function (id) { return BY_ID[id]; });
      // picker state
      $$("[data-opt]", list).forEach(function (b) {
        var i = ids.indexOf(b.getAttribute("data-opt"));
        b.setAttribute("aria-pressed", i > -1 ? "true" : "false");
        b.style.setProperty("--c", i > -1 ? colors[i] : "");
        b.disabled = i === -1 && ids.length >= MAX;
      });
      if (pickedLbl) pickedLbl.textContent = "(" + ids.length + "/" + MAX + ")";
      try { history.replaceState(null, "", ids.length ? "#ids=" + ids.join(",") : location.pathname); } catch (e) { /* file:// */ }

      if (items.length < 2) {
        out.innerHTML = '<div class="cmp-empty"><h2>Pick ' + (items.length ? "one more power station" : "at least two power stations") + '</h2><p class="muted">Tap the power stations above to add them. You can compare up to ' + MAX + " at once.</p></div>";
        return;
      }

      // wins per product (count of best rows)
      var wins = items.map(function () { return 0; });
      var bodyRows = "";
      DB.meta.groups.forEach(function (g) {
        bodyRows += '<tr class="grp"><th colspan="' + (items.length + 1) + '">' + esc(g.name) + "</th></tr>";
        g.rows.forEach(function (r) {
          var vals = items.map(function (p) { return p.specs[r.k]; });
          var best = [];
          if (r.better) {
            var cands = vals.map(function (v, i) { return { v: v, i: i }; }).filter(function (o) { return o.v != null && o.v !== ""; });
            if (r.better === "true") {
              var t = cands.filter(function (o) { return o.v === true; });
              if (t.length && t.length < items.length) best = t.map(function (o) { return o.i; });
            } else if (cands.length > 1) {
              var target = r.better === "max" ? Math.max.apply(null, cands.map(function (o) { return o.v; })) : Math.min.apply(null, cands.map(function (o) { return o.v; }));
              var hits = cands.filter(function (o) { return o.v === target; });
              if (hits.length < cands.length) best = hits.map(function (o) { return o.i; });
            }
          }
          best.forEach(function (i) { wins[i]++; });
          var shown = vals.map(function (v) { return JSON.stringify(v); });
          var same = shown.every(function (v) { return v === shown[0]; });
          bodyRows += '<tr class="' + (same ? "is-same" : "") + '"><th scope="row">' + esc(r.label) + "</th>" +
            vals.map(function (v, i) { return '<td class="' + (best.indexOf(i) > -1 ? "is-best" : "") + '">' + fmt(v, r.unit) + "</td>"; }).join("") + "</tr>";
        });
      });
      // scores block in table
      bodyRows += '<tr class="grp"><th colspan="' + (items.length + 1) + '">Editor scores (0–10)</th></tr>';
      DB.meta.axes.forEach(function (a) {
        var vals = items.map(function (p) { return p.scores[a.k]; });
        var valid = vals.filter(function (v) { return v != null; });
        var mx = valid.length ? Math.max.apply(null, valid) : null;
        var allSame = valid.length === vals.length && valid.every(function (v) { return v === valid[0]; });
        bodyRows += '<tr class="' + (allSame ? "is-same" : "") + '"><th scope="row">' + esc(a.label) + "</th>" + vals.map(function (v) {
          return '<td class="' + (!allSame && v != null && v === mx ? "is-best" : "") + '">' + (v == null ? '<span class="na">n/a</span>' : v) + "</td>";
        }).join("") + "</tr>";
      });

      var head = '<tr><th scope="col"><span class="sr">Spec</span></th>' + items.map(function (p, i) {
        return '<th scope="col"><div class="cmp-head" style="--c:' + colors[i] + '"><div class="cmp-head__img"><img src="' + esc(p.img) + '" alt=""><button type="button" class="cmp-head__rm" data-rm="' + esc(p.id) + '" aria-label="Remove ' + esc(p.name) + '"><svg class="ico"><use href="#i-x"/></svg></button></div>' +
          '<a class="cmp-head__name" href="' + esc(p.url) + '">' + esc(p.name) + "</a>" +
          (p.price != null ? '<span class="cmp-head__price">' + money(p.price) + '</span><span class="price__date">as of ' + esc(p.priceDate) + "</span>" : "") +
          '<a class="btn btn--amazon btn--xs" href="' + esc(p.aff) + '" target="_blank" rel="sponsored nofollow noopener">View on Amazon<svg class="ico"><use href="#i-ext"/></svg></a></div></th>';
      }).join("") + "</tr>";

      var sums = items.map(function (p, i) {
        return '<div class="cmp-sum" style="--c:' + colors[i] + '"><h3>' + esc(p.name) + '</h3><span class="score-pill">' + p.score + "</span><p>" +
          (p.rating != null ? p.rating.toFixed(1) + "★ on Amazon (" + num(p.reviews) + ")" : "No Amazon reviews yet") +
          '</p><p class="wins"><b>' + wins[i] + "</b> best-in-row spec" + (wins[i] === 1 ? "" : "s") + '</p><p class="cmp-sum__tag">' + esc(p.verdict) + '</p><a class="btn btn--amazon btn--xs btn--block" href="' + esc(p.aff) + '" target="_blank" rel="sponsored nofollow noopener">View on Amazon<svg class="ico"><use href="#i-ext"/></svg></a></div>';
      }).join("");

      var legend = items.map(function (p, i) { return '<li><i style="--c:' + colors[i] + '"></i>' + esc(p.name) + "</li>"; }).join("");

      out.innerHTML =
        '<div class="cmp-top"><div class="cmp-chart">' + radar(items.map(function (p, i) { return { scores: p.scores, color: colors[i], name: p.name }; }), 380) +
        '<ul class="legend">' + legend + '</ul>' + '<a class="link-arrow cmp-maplink" href="/calculator/?ids=' + items.map(function (p) { return encodeURIComponent(p.id); }).join(",") + '">Check them in the runtime calculator<svg class="ico"><use href="#i-arrow"/></svg></a>' + '</div><div class="cmp-summary">' + sums + "</div></div>" +
        '<div class="cmp-table-wrap"><div class="cmp-table-tools"><h2>Spec by spec</h2><label class="switch"><input type="checkbox" data-diff' + (showAll ? "" : " checked") + '> Only show differences</label></div>' +
        '<div class="table-scroll"><table class="cmp-table' + (showAll ? " show-all" : "") + '" style="min-width:' + (130 + items.length * 175) + 'px"><colgroup><col class="c-label">' + items.map(function () { return "<col>"; }).join("") + '</colgroup><thead>' + head + "</thead><tbody>" + bodyRows + "</tbody></table></div></div>" +
        '<p class="note note--muted">“Best” marks the strongest value in each row (more capacity, output, solar input and cycles; lower weight, noise and charge time). A dash means the value isn’t published. Scores are editorial — see <a href="/how-we-rate/">how we rate</a>.</p>';
    }
  }

  function boot() {
    safe(initNav, "nav");
    safe(initCompareToggles, "compare");
    safe(initGallery, "gallery");
    safe(initSort, "sort");
    safe(initStickyBuy, "sticky");
    safe(initComparator, "comparator");
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
})();
